"""Analyze local-relationship differences across Georgia Queen-adjacency edges.

This is the first GR-GWR regime-identification diagnostic after standard GWR.
It consumes the local coefficients generated by the repository's own BasicGWR
Georgia baseline and deliberately excludes the intercept from the regime
fingerprint.

For county i, the local relationship fingerprint is

    f_i = z([beta_PctFB, beta_PctBlack, beta_PctRural])

where each slope surface is standardized across the 159 counties (ddof=0).
For each of the 431 undirected Queen edges (i, j), we then compute

    d_ij = ||f_i - f_j||_2.

The Queen graph constrains which pairs are compared; geographic coordinates are
not appended to the fingerprint, so spatial proximity is not counted twice.

Outputs
-------
- local_relationship_fingerprints.csv
- queen_edge_relationship_distances.csv
- county_boundary_intensity.csv
- summary.json
- georgia_local_relationship_edge_differences.png/.svg
"""

from __future__ import annotations

import json
from pathlib import Path

import geopandas as gpd
import matplotlib.pyplot as plt
from matplotlib.collections import LineCollection
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
COEFFICIENTS = (
    ROOT
    / "results"
    / "real_data"
    / "georgia_gwr_baseline"
    / "basicgwr_local_coefficients.csv"
)
EDGES = ROOT / "results" / "spatial" / "georgia_queen_w" / "edge_list.csv"
SHP = ROOT / "data" / "raw" / "georgia" / "G_utm.shp"
OUT = ROOT / "results" / "spatial" / "georgia_local_relationship_edges"

SLOPES = ["PctFB", "PctBlack", "PctRural"]
ZCOLS = [f"z_{name}" for name in SLOPES]


def _canonical_key(series: pd.Series) -> pd.Series:
    return pd.to_numeric(series, errors="raise").astype(int).astype(str)


def _build_fingerprints(coef: pd.DataFrame) -> pd.DataFrame:
    missing = [c for c in ["AreaKey", *SLOPES] if c not in coef.columns]
    if missing:
        raise RuntimeError(f"Missing BasicGWR coefficient columns: {missing}")
    if len(coef) != 159:
        raise RuntimeError(f"Expected 159 Georgia coefficient rows; got {len(coef)}")

    out = coef[["AreaKey", *SLOPES]].copy()
    out["AreaKey"] = _canonical_key(out["AreaKey"])

    for slope, zcol in zip(SLOPES, ZCOLS):
        values = out[slope].to_numpy(dtype=float)
        mean = float(np.mean(values))
        std = float(np.std(values, ddof=0))
        if not np.isfinite(std) or std <= 0.0:
            raise RuntimeError(f"Cannot standardize {slope}: std={std}")
        out[zcol] = (values - mean) / std

    if out[ZCOLS].isna().any().any():
        raise RuntimeError("NaN encountered in standardized local relationship fingerprints")
    return out


def _edge_distances(edges: pd.DataFrame, fp: pd.DataFrame) -> pd.DataFrame:
    required = ["AreaKey_i", "AreaKey_j"]
    missing = [c for c in required if c not in edges.columns]
    if missing:
        raise RuntimeError(f"Missing Queen edge columns: {missing}")
    if len(edges) != 431:
        raise RuntimeError(f"Expected 431 undirected Queen edges; got {len(edges)}")

    work = edges.copy()
    work["AreaKey_i"] = _canonical_key(work["AreaKey_i"])
    work["AreaKey_j"] = _canonical_key(work["AreaKey_j"])

    left = fp[["AreaKey", *ZCOLS]].rename(
        columns={"AreaKey": "AreaKey_i", **{c: f"{c}_i" for c in ZCOLS}}
    )
    right = fp[["AreaKey", *ZCOLS]].rename(
        columns={"AreaKey": "AreaKey_j", **{c: f"{c}_j" for c in ZCOLS}}
    )
    work = work.merge(left, on="AreaKey_i", how="left", validate="many_to_one")
    work = work.merge(right, on="AreaKey_j", how="left", validate="many_to_one")

    delta_cols = []
    for zcol in ZCOLS:
        dcol = f"delta_{zcol.removeprefix('z_')}"
        work[dcol] = work[f"{zcol}_i"] - work[f"{zcol}_j"]
        delta_cols.append(dcol)

    work["coef_distance"] = np.sqrt(
        np.sum(np.square(work[delta_cols].to_numpy(dtype=float)), axis=1)
    )
    if work["coef_distance"].isna().any():
        raise RuntimeError("NaN encountered in Queen-edge coefficient distances")

    return work


def _county_boundary_intensity(edge_df: pd.DataFrame) -> pd.DataFrame:
    left = edge_df[["AreaKey_i", "coef_distance"]].rename(
        columns={"AreaKey_i": "AreaKey"}
    )
    right = edge_df[["AreaKey_j", "coef_distance"]].rename(
        columns={"AreaKey_j": "AreaKey"}
    )
    stacked = pd.concat([left, right], ignore_index=True)
    out = (
        stacked.groupby("AreaKey", as_index=False)["coef_distance"]
        .agg(["mean", "max", "count"])
        .reset_index()
        .rename(
            columns={
                "mean": "mean_neighbor_distance",
                "max": "max_neighbor_distance",
                "count": "queen_degree",
            }
        )
    )
    return out


def _plot(gdf: gpd.GeoDataFrame, edge_df: pd.DataFrame, intensity: pd.DataFrame) -> None:
    shp_key = next((c for c in gdf.columns if str(c).lower() == "areakey"), None)
    if shp_key is None:
        raise RuntimeError("AreaKey not found in Georgia shapefile")

    mapped = gdf.copy()
    mapped["AreaKey_join"] = _canonical_key(mapped[shp_key])
    centroids = mapped.set_index("AreaKey_join").geometry.centroid

    segments = []
    values = []
    for row in edge_df.itertuples(index=False):
        p0 = centroids.loc[str(row.AreaKey_i)]
        p1 = centroids.loc[str(row.AreaKey_j)]
        segments.append([(p0.x, p0.y), (p1.x, p1.y)])
        values.append(float(row.coef_distance))

    fig, axes = plt.subplots(1, 2, figsize=(17.0, 8.3))

    # (a) Queen edges colored by standardized slope-fingerprint distance.
    ax = axes[0]
    mapped.boundary.plot(ax=ax, linewidth=0.35, color="0.72")
    collection = LineCollection(
        segments,
        array=np.asarray(values, dtype=float),
        cmap="viridis",
        linewidths=1.6,
        alpha=0.95,
    )
    ax.add_collection(collection)
    cbar = fig.colorbar(collection, ax=ax, fraction=0.036, pad=0.02)
    cbar.set_label(r"$d_{ij}^{coef}$")
    ax.set_title("(a) Queen-edge local relationship difference", fontsize=14)
    ax.set_aspect("equal")
    ax.set_axis_off()

    # (b) County-level mean difference to its Queen neighbors.
    intensity2 = intensity.copy()
    intensity2["AreaKey"] = _canonical_key(intensity2["AreaKey"])
    mapped = mapped.merge(
        intensity2,
        left_on="AreaKey_join",
        right_on="AreaKey",
        how="left",
        validate="1:1",
    )
    ax = axes[1]
    mapped.plot(
        column="mean_neighbor_distance",
        ax=ax,
        cmap="viridis",
        legend=True,
        edgecolor="black",
        linewidth=0.28,
        legend_kwds={"label": "Mean adjacent coefficient distance", "shrink": 0.72},
    )
    ax.set_title("(b) County boundary-intensity diagnostic", fontsize=14)
    ax.set_aspect("equal")
    ax.set_axis_off()

    fig.suptitle(
        "Georgia local relationship differences from BasicGWR slopes + Queen adjacency",
        fontsize=16,
        y=0.985,
    )
    fig.tight_layout()

    fig.savefig(OUT / "georgia_local_relationship_edge_differences.png", dpi=300, bbox_inches="tight")
    fig.savefig(OUT / "georgia_local_relationship_edge_differences.svg", bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    coef = pd.read_csv(COEFFICIENTS)
    edges = pd.read_csv(EDGES)
    gdf = gpd.read_file(SHP)

    fp = _build_fingerprints(coef)
    edge_df = _edge_distances(edges, fp)
    intensity = _county_boundary_intensity(edge_df)

    fp.to_csv(OUT / "local_relationship_fingerprints.csv", index=False)
    edge_df.to_csv(OUT / "queen_edge_relationship_distances.csv", index=False)
    intensity.to_csv(OUT / "county_boundary_intensity.csv", index=False)

    distances = edge_df["coef_distance"].to_numpy(dtype=float)
    quantiles = np.quantile(distances, [0.0, 0.25, 0.5, 0.75, 0.9, 0.95, 1.0])
    top_edges = edge_df.nlargest(10, "coef_distance")[[
        "AreaKey_i", "AreaKey_j", "coef_distance", "delta_PctFB", "delta_PctBlack", "delta_PctRural"
    ]]

    summary = {
        "n_counties": int(len(fp)),
        "n_queen_edges": int(len(edge_df)),
        "fingerprint_terms": SLOPES,
        "intercept_used_in_fingerprint": False,
        "coordinates_used_in_fingerprint": False,
        "coefficient_standardization": "column-wise z-score, ddof=0",
        "edge_distance": "Euclidean distance between standardized slope fingerprints",
        "distance_mean": float(np.mean(distances)),
        "distance_std": float(np.std(distances, ddof=0)),
        "distance_min": float(quantiles[0]),
        "distance_q25": float(quantiles[1]),
        "distance_median": float(quantiles[2]),
        "distance_q75": float(quantiles[3]),
        "distance_q90": float(quantiles[4]),
        "distance_q95": float(quantiles[5]),
        "distance_max": float(quantiles[6]),
        "top_10_edges": top_edges.to_dict(orient="records"),
    }
    (OUT / "summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    _plot(gdf, edge_df, intensity)

    print(json.dumps(summary, indent=2, ensure_ascii=False))
    print(f"Generated: {(OUT / 'georgia_local_relationship_edge_differences.png').relative_to(ROOT)}")
    print(f"Generated: {(OUT / 'georgia_local_relationship_edge_differences.svg').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
